import numpy as np
import tensorflow as tf
from sklearn.preprocessing import MinMaxScaler
from pathlib import Path

from converter.to_tflite import OPTIMIZERS, export

"""Your current script is using a technique called Surrogate 
Modeling (or a Student-Teacher network). Because PyOD’s 
DeepSVDD is built on PyTorch, you cannot directly export 
it to TFLite. Instead, your script cleverly uses Keras to 
train a brand-new "student" network to mimic the anomaly scores 
(y_train) generated by the PyOD "teacher."However, because DeepSVDD 
relies on spherical distance in a latent space, forcing a standard 
Dense(1) regression layer to learn that complex geometry can result in 
a lot of accuracy loss.To fix this, you should change the architecture 
of your Keras surrogate so it performs the exact same mathematical 
operations as DeepSVDD (mapping to a latent space, then calculating the 
Euclidean distance to a center point $c$).Here is how you adapt your Keras 
architecture and ensure it remains int8 compatible for the microcontroller."""

class _ProgressCallback(tf.keras.callbacks.Callback):
    """Reports 1-indexed epoch progress via a plain callable, and stops
    training early (at the next epoch boundary) if cancel_event is set.
    """

    def __init__(self, progress_callback, total_epochs, cancel_event=None):
        super().__init__()
        self._progress_callback = progress_callback
        self._total_epochs = total_epochs
        self._cancel_event = cancel_event

    def on_epoch_end(self, epoch, logs=None):
        if self._progress_callback is not None:
            self._progress_callback(epoch + 1, self._total_epochs)
        if self._cancel_event is not None and self._cancel_event.is_set():
            self.model.stop_training = True


def to_tflite_deep_svdd(name, x_train, y_train, x_test, y_test,
                        layers, latent_dim, learning_rate, epochs, batch_size, verbose,
                        feature_names=None, output_dir=None, progress_callback=None,
                        cancel_event=None, loss="mse", optimizer="adam",
                        quantization="int8", flag_fraction=0.1):
    """Fit a DeepSVDD-shaped surrogate on anomaly scores and export .tflite
    plus ``<name>_params.json``; ``quantization`` and ``flag_fraction`` are
    as in ``converter.to_tflite.to_tflite``.

    ``output_dir`` defaults to ``./.tflite`` (the original notebook behavior)
    when not given. ``progress_callback``, if given, is called as
    ``progress_callback(epoch, total_epochs)`` after each training epoch.
    ``cancel_event``, if given and set, stops training at the next epoch
    boundary and skips writing any output files, returning None instead of
    the model.
    """

    # Normalize the input features
    input_scaler = MinMaxScaler().fit(x_train)
    x_train = input_scaler.transform(x_train).astype("float32")
    x_test = input_scaler.transform(x_test).astype("float32")

    # 1. Build the Encoder (maps input to latent space)
    inputs = tf.keras.Input(shape=(x_train.shape[1],))
    x = inputs
    for units in layers:
        x = tf.keras.layers.Dense(units, activation="relu")(x)
    
    # 2. The Latent Representation (e.g., 32 dimensions)
    # We use linear activation here (no ReLU) to allow free movement in the hypersphere
    latent = tf.keras.layers.Dense(latent_dim, activation="linear", use_bias=False)(x)

    # 3. The Learned Center (c)
    # We create 'c' as a trainable weight so the Keras model can shift it dynamically 
    # to best match the PyOD anomaly scores.
    c = tf.Variable(initial_value=tf.random.normal([latent_dim]), 
                    trainable=True, 
                    dtype=tf.float32, 
                    name="hypersphere_center")

    # 4. Calculate Squared Euclidean Distance (Anomaly Score)
    # (latent - c)^2 summed across the dimensions
    distance = tf.reduce_sum(tf.square(latent - c), axis=1, keepdims=True)

    # Compile the model
    model = tf.keras.Model(inputs=inputs, outputs=distance)
    
    # MSE (the default) fits best here, since we are trying to make our Keras
    # distance output match the PyOD anomaly score (y_train) perfectly.
    model.compile(
        optimizer=OPTIMIZERS[optimizer](learning_rate=learning_rate),
        loss=loss,
    )
    
    callbacks = []
    if progress_callback is not None or cancel_event is not None:
        callbacks.append(_ProgressCallback(progress_callback, epochs, cancel_event))

    model.fit(
        x_train,
        y_train,
        validation_data=(x_test, y_test),
        epochs=epochs,
        batch_size=batch_size,
        verbose=verbose,
        callbacks=callbacks,
    )

    if cancel_event is not None and cancel_event.is_set():
        return None

    out_dir = Path(output_dir) if output_dir is not None else Path(".tflite")
    # tf.square and tf.reduce_sum are fully supported by TFLite int8 built-ins
    export(model, name, out_dir, x_train, x_test, input_scaler,
           quantization, feature_names, flag_fraction)

    return model